def t_presets():
    js = _read_js("web/src/main.js")
    defaults = _pairs(_block(js, "DEFAULTS"))
    base = _pairs(_block(js, "PRESET_BASE"))
    src = _block(js, "PRESETS")

    def val(s):
        if s == "true":
            return True
        if s == "false":
            return False
        try:
            return float(s)
        except ValueError:
            return s

    base_v = {k: val(v) for k, v in base.items()}
    def_v = {k: val(v) for k, v in defaults.items()}
    base_diff = {k: v for k, v in base_v.items() if def_v.get(k) != v}

    body = []
    seen = 0
    for m in re.finditer(r"'([^']+)'\s*:\s*\{([^}]*)\}", src, re.S):
        name = m.group(1)
        pairs = re.findall(r"(\w+)\s*:\s*([-\w.]+)", m.group(2))
        eff = dict(base_v)
        eff.update({k: val(v) for k, v in pairs})
        delta = [(k, v) for k, v in eff.items() if def_v.get(k) != v]
        txt = ", ".join("\\texttt{%s=%s}" % (k.replace("_", "\\_"), fmt(v))
                        for k, v in delta)
        if not txt:
            txt = "--"
        body.append("%s & %s \\\\" % (texify(name), txt))
        seen += 1
    if seen != 7:
        raise RuntimeError("expected 7 presets, found %d" % seen)
    w("t14_presets.tex", body,
      "七个出厂预设的净效果。每个预设先加载公共基线 \\texttt{PRESET\\_BASE}"
      "（对全部 %d 个参数的显式赋值，其中相对 \\texttt{DEFAULTS} 仅 %s），"
      "再叠加本表所列覆盖；因此切换预设不会继承上一个预设的任何残留状态。"
      "表内只显示与 \\texttt{DEFAULTS} 不同的键，由脚本解析源码生成。"
      % (len(base_v),
         "、".join("\\texttt{%s=%s}" % (k.replace("_", "\\_"), fmt(v))
                   for k, v in sorted(base_diff.items()))),
      "tab:presets", 2, ["预设", "相对 \\texttt{DEFAULTS} 的净差异"],
      size="\\scriptsize",
      align="p{0.20\\linewidth}p{0.72\\linewidth}")


