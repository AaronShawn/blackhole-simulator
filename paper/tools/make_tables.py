def _read_js(relpath):
    with open(os.path.join(ROOT, relpath), encoding="utf-8") as fh:
        return fh.read()


def _block(src, name):
    m = re.search(r"const %s\s*=\s*\{(.*?)\n\};" % name, src, re.S)
    if not m:
        raise RuntimeError("cannot locate const %s in main.js" % name)
    return m.group(1)


def _pairs(block):
    """Parse a JS object-literal body into a ``{key: "literal"}`` dict.

    ``//`` comments and spread entries (``...PRESET_BASE``) carry no colon and
    are therefore skipped by the pair regex, which is exactly what the preset
    table needs: it wants the explicitly written keys of each literal only.
    """
    out = {}
    for line in block.splitlines():
        line = re.sub(r"//.*$", "", line)
        for key, value in re.findall(r"(\w+)\s*:\s*([-\w.]+)", line):
            out[key] = value
    return out


def fmt(v):
    """Format a parsed JS literal for use inside ``\\texttt{}``."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return v
    if abs(v - round(v)) < 1e-12 and abs(v) < 1e5:
        return "%d" % round(v)
    if abs(v) >= 1e5:
        mantissa, exponent = ("%.1e" % v).split("e")
        return "%se%d" % (mantissa, int(exponent))
    return "%g" % v


