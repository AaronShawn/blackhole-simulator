def jload(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return json.load(fh)


def sciraw(x, d=3):
    """Scientific notation body (no math delimiters) with ``d`` digits."""
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10.0 ** e
    if m >= 10.0:
        m /= 10.0
        e += 1
    if m < 1.0:
        m *= 10.0
        e -= 1
    return "%.*f\\times 10^{%d}" % (d, m, e)


def sci(x, d=3):
    """LaTeX scientific notation; wraps :func:`sciraw` in math mode."""
    return "$%s$" % sciraw(x, d)


def rel(x, d=2):
    return "$%+.*f\\%%$" % (d, 100.0 * x)


def num(x, d=3):
    return "%.*f" % (d, x)


def px(x, d=2):
    """Signed pixel offset, or an em-dash when the local frame is degenerate."""
    if x is None:
        return "--"
    return "$%+.*f$" % (d, x)


_SUP = {
    "\u2070": "0", "\u00b9": "1", "\u00b2": "2", "\u00b3": "3", "\u2074": "4",
    "\u2075": "5", "\u2076": "6", "\u2077": "7", "\u2078": "8", "\u2079": "9",
    "\u207a": "+", "\u207b": "-",
}


def texify(s):
    """Rewrite literal superscripts into math superscripts for the PDF body.

    Preset names are shown verbatim in the application UI (``T=10\u2077 K``), but the
    text fonts used by the paper have no U+2077 glyph, so the table build turns
    any run of superscript characters into ``$^{7}$``.  Without this the
    compiler only warns and silently drops the character from the table.
    """
    out, buf = [], []
    for ch in s:
        if ch in _SUP:
            buf.append(_SUP[ch])
            continue
        if buf:
            out.append("$^{%s}$" % "".join(buf))
            buf = []
        out.append(ch)
    if buf:
        out.append("$^{%s}$" % "".join(buf))
    return "".join(out)


def w(name, body, caption, label, cols, head, size="\\small",
      align=None, extra=""):
    align = align or ("l" + "r" * (len(head) - 1))
    lines = [
        "%% generated by tools/make_tables.py -- do not edit",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{%s}" % caption,
        "\\label{%s}" % label,
        size,
        "\\begin{tabular}{%s}" % align,
        "\\toprule",
        " & ".join(head) + " \\\\",
        "\\midrule",
    ]
    lines += body
    lines += ["\\bottomrule", "\\end{tabular}", extra, "\\end{table}", ""]
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("[tbl] %-26s %3d rows" % (name, len(body)))
    return path


